"""W1 纵切 harness：gold 先加载 → 跑桩 → 人工确认 → 审计 → 输出 PASS/FAIL。

用法：python scripts/vertical_slice.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from ticketdesk import pipeline  # noqa: E402
from ticketdesk.tools import Session  # noqa: E402

GOLD = ROOT / "fixtures" / "gold"
SESSION = Session(customer_id="C-1001")
CHECKS = []


def check(name, ok, detail=""):
    CHECKS.append(ok)
    print("[%s] %s%s" % ("PASS" if ok else "FAIL", name, "：" + detail if detail else ""))
    return ok


def main():
    # 1 gold 必须在执行前就存在，且只读
    gold_path = GOLD / "T-1001.json"
    gold_loaded = gold_path.exists()
    gold = json.loads(gold_path.read_text(encoding="utf-8")) if gold_loaded else {}
    check("expectation loaded before execution", gold_loaded,
          "%s（冻结于 %s）" % (gold_path.name, gold.get("frozen_at")))

    # 2 跑纵切（stub 不读 gold）
    evidence = pipeline.build_evidence("T-1001", SESSION)
    decision = pipeline.stub_decide(evidence)
    check("decision generated by deterministic stub",
          decision["verdict"] == "DECIDED", decision["reason"])

    # 3 证据可回查 + 引用都落在真实 fact_id 上
    cited = set(decision["cited_facts"])
    real = {item["fact_id"] for item in evidence["facts"]}
    traceable = cited and cited <= real
    check("evidence traceable by fact_id", traceable,
          "引用 %s / 共 %d 条" % (sorted(cited), len(evidence["facts"])))

    # 4 与 gold 比较（gold 只在这一步被读，从未被写）
    match = (decision["queue"] == gold.get("gold_queue")
             and decision["priority"] == gold.get("gold_priority"))
    fields = {item["field"] for item in evidence["facts"]}
    needed = set(gold.get("required_facts", []))
    check("decision matches frozen gold", match,
          "判定 %s/%s vs gold %s/%s" % (decision["queue"], decision["priority"],
                                       gold.get("gold_queue"), gold.get("gold_priority")))
    check("required facts present", needed <= fields, "缺 %s" % sorted(needed - fields))

    # 5 人工确认 before/after
    confirmation = pipeline.human_confirm(decision, "ACCEPT", final_queue="履约组")
    keys_ok = {"model_output", "human_action", "final_output",
               "changed_fields", "timestamp"} <= set(confirmation)
    check("human confirmation audited", keys_ok,
          "changed=%s" % confirmation["changed_fields"])

    # 6 审计时间线区分 occurred_at / recorded_at
    events = pipeline.audit_events(evidence, decision, confirmation)
    timeline_ok = bool(events) and all(
        {"event_type", "occurred_at", "recorded_at"} <= set(item) for item in events
    )
    kinds = sorted({item["event_type"] for item in events})
    check("audit timeline complete", timeline_ok, "%d 条事件 %s" % (len(events), kinds))

    # 7 争议 case 能被系统容纳（W1 只证明容纳，不判定是否 Agent-needed）
    ambiguous = pipeline.stub_decide(pipeline.build_evidence("T-1003", SESSION))
    check("ambiguous case can be carried", ambiguous["ambiguous"] is True,
          "%s / needs_human=%s" % (ambiguous["verdict"], ambiguous["needs_human"]))

    # 8 失败转人工
    missing = pipeline.stub_decide(pipeline.build_evidence("T-1004", SESSION))
    check("failure handoff audited", missing["needs_human"] is True,
          "%s / %s" % (missing["verdict"], missing["reason"]))

    print("---- W1 vertical slice: %s ----"
          % ("PASS" if all(CHECKS) else "FAIL"))
    return 0 if all(CHECKS) else 1


if __name__ == "__main__":
    sys.exit(main())
